"""Synthèse and Détail (the views page) for Skywise / Slate, two ways. Writes 03_reports/skywise/views/.

Way 1, JavaScript only in the page (way1_js_in_page/): one code sandbox does everything. The Slate queries hand it the two
tables (q_fto2_nc, q_fto2_def, the same as the dashboard's level 3); the page's JavaScript reads them (fto2FromTables) and
computes and draws every figure. It is the dashboard template in its 'vues' mode: same charts, same numbers as the dashboard.

Way 2, pre-computed by a Slate function (way2_precomputed/): queries (data) -> one Slate function (logic) -> code sandbox
(display). The function f_fto2_views holds the views' model (fto2_views_model.js: pure JavaScript, no page, no drawing) and
returns every number, series and table the views show, for the filters the sandbox sends back through the variable
v_fto2_filters; the sandbox only draws. build/views/build_way2.py assembles both from the dashboard template. The same model
file runs in Node to pre-compute the views outside Slate (precompute_node.js).

    python3 -I build/views_pack.py        (also run by build_all.py)

Reads the dashboard's own data block (03_reports/FTO2_NC_Dashboard.html: the two tables and the fixed references), so it needs
no other input; the local previews carry the real tables, the Slate files carry only the references.
"""
import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import build_all        # noqa: E402   _scope_css: the dashboard's styles scoped to .fto2
import skywise_pack as SP  # noqa: E402   the Slate pieces of the dashboard (CSS, HTML, main script, table adapter, app format)

OUT = os.path.join(ROOT, "03_reports", "skywise", "views")
L3 = os.path.join(ROOT, "03_reports", "skywise", "level3_datasets")


def dash_data():
    """The main page's data block: {'tables': {nc, def, dis}, 'ref': {...}}."""
    src = open(os.path.join(ROOT, "03_reports", "FTO2_NC_Dashboard.html"), encoding="utf-8").read()
    a = src.index("window.DASH = ") + len("window.DASH = ")
    b = src.index(";\nwindow.FTO2_PAGE", a)
    return json.loads(src[a:b].replace("<\\/", "</"))


def way1(data, say=print):
    out = os.path.join(OUT, "way1_js_in_page")
    css, html, main, adapter = SP.parts(ROOT, build_all._scope_css)
    stamp = ("FTO2 Synthèse et détail, way 1 (JavaScript only in the page): data from the Slate queries q_fto2_nc, q_fto2_def and q_fto2_dis "
             "(optional) through the code sandbox's state. Generated by build/views_pack.py; do not edit by hand.")
    head = "window.FTO2_PAGE = 'main';"
    assert SP.JS_L23.count(head) == 1
    js = SP._sub(SP.JS_L23.replace(head, "window.FTO2_PAGE = 'vues';"), stamp=stamp, ref=SP._blob(data["ref"]), adapter=adapter, main=main)
    one = SP.write_level(out, "fto2_views", stamp, "FTO2 Synthèse et détail - way 1", css, html, js)
    open(os.path.join(out, "FTO2_Views_Slate.html"), "w", encoding="utf-8").write(one)
    json.dump(SP.STATE, open(os.path.join(out, "state.json"), "w"), indent=2)
    sql = []
    for q in ("q_fto2_nc", "q_fto2_def", "q_fto2_dis"):   # the dashboard's level-3 queries, unchanged
        shutil.copyfile(os.path.join(L3, q + ".sql"), os.path.join(out, q + ".sql"))
        sql.append((q, open(os.path.join(L3, q + ".sql"), encoding="utf-8").read()))
    app = SP.slate_app("FTO2 Synthèse et détail", css, html, js, sql)
    json.dump(app, open(os.path.join(out, "FTO2_Views_way1.slate.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    # local preview: the real tables handed over as Slate would (never paste this file into Slate)
    t = data["tables"]
    pre = SP.FAKE_SLATE.replace("@@NC@@", SP._blob(t["nc"])).replace("@@DEF@@", SP._blob(t["def"])).replace("@@DIS@@", SP._blob(t.get("dis") or {}))
    open(os.path.join(out, "preview_local_only.html"), "w", encoding="utf-8").write(
        one.replace("<!-- ===== HTML START ===== -->", pre + "<!-- ===== HTML START ===== -->", 1))
    say("views way 1:", {f: os.path.getsize(os.path.join(out, f)) // 1024 for f in sorted(os.listdir(out))}, "KB")


def build(say=print):
    data = dash_data()
    way1(data, say)
    w2 = os.path.join(HERE, "views", "build_way2.py")
    if os.path.exists(w2):
        sys.path.insert(0, os.path.dirname(w2))
        import build_way2   # noqa: E402
        build_way2.build(data, OUT, say)


if __name__ == "__main__":
    build()
