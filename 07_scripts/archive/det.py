import re, unicodedata
def N(s): return ''.join(c for c in unicodedata.normalize('NFD',str(s)) if unicodedata.category(c)!='Mn').upper()
R = lambda p: re.compile(p)
DET = {
 'SHORT':    R(r"TROP COURT|\bCOURTS?\b(?!-?CIRCUIT)|\bCOURTES?\b|LONGUEUR INSUFFISANTE|PAS ASSEZ LONG|\bSHORT\b(?! CIRCUIT)|RACCOURCI"),
 'LONG':     R(r"TROP LONGS?\b|SUR-?LONGUEUR|\bTOO LONG\b"),
 'MISSING':  R(r"MANQUANT|\bMANQUE\b|MANQUENT|\bMQ\b|PAS (ETE )?LIVRE|NON LIVRE|NON RECU|PAS RECU|NE TROUVE PAS|NE TROUVONS PAS|INTROUVABLE|\bABSENT|\bMISSING|PAS PRESENT|NON PRESENT|NON SERVI|PAS SERVI"),
 'SEVERED':  R(r"\bCOUPE(E|S|ES)?\b(?!\s*(A LA BONNE|TROP COURT|COURT|TROP|\())|SECTIONNE|\bCABLE CUT\b|\bCUT\b"),
 'DAMAGED':  R(r"ABIME|ENDOMMAG|DENUDE|ECRASE|\bPINCE|BLESS|DETERIOR|ARRACHE|DEFAUT (SUR )?L.?ISOLANT|ISOLANT (ABIME|ENDOMMAGE|PERCE)|OXYD|DAMAGED|ECORCHE|ENTAILLE|FENDU|PERCE"),
 'SPEC':     R(r"MAUVAISE JAUGE|ERREUR DE JAUGE|JAUGE (NON CONFORME|ERRONEE|INCORRECTE)|LASERIS|NON LASER|REPERAGE|MARQUAGE|ILLISIBLE|MAUVAIS(E)? (TYPE|NUMERO|REFERENCE|REF\b|CABLE|COULEUR)|TYPE DE CABLE|MAUVAIS NUMERO|ERREUR D.?IMPRESSION AU NIVEAU|IDENTIFICATION NON CONFORME|MAL IMPRIME|IMPRESSION (NON CONFORME|ERRONEE|DEFECTUEUSE)|MAUVAIS REPERE|WRONG GAUGE"),
 'WORKMANSHIP': R(r"\bSERTI|NON SERTI|MAL SERTI|SERTISSAGE"),
}
PROV = {
 'UPSTREAM': R(r"\bRECUS?\b|\bRECUT\b|RECU(E|ES)?\b|FOURNI|\bSERVIS?\b|DE L.?IMPRESSION|SALLE (D.?)?IMPRESSION|RAPID ?SHARE|RAPIDSHARE|MACHINE|A LA RECEPTION|DEBALLAGE|PAS (ETE )?LIVRE|NON LIVRE|LIVRE DANS|DANS LE FAISCEAU|DANS LE KIT|NON LASER|LASERIS"),
 'LINE':     R(r"PAR (LA )?PROD|PRODUCTION|PRODUCITON|PORDUCTION|OPERATEUR|OPERATRICE|COMPAGNON|MISE EN OEUVRE|\bMEO\b|CHEMINEMENT|RETOUCHE|PAR ERREUR|SUR TABLE|\bPROD\b|POSTE MECA|AU POSTE"),
}
def detect(txt):
    n = N(txt)
    return {k for k,p in DET.items() if p.search(n)}, {k for k,p in PROV.items() if p.search(n)}
