"""Tableau Elizabeth (30 Oct): the NC count and three families, a Pareto and the weeks over a threshold (10 NC per week by default).

Families, each counted in NCs (an NC counts once in a family when one of its defect lines belongs to it): Branchement (category
"Erreur Branchement"), Déverrouillage (category "Déverrouillage"), Câbles (a cable defect: the cable itself to remake or resupply,
the `cable` column). Scope as the MFT page: NCs raised at FTO2 (plant FTO2 or FT02) created in 2026; line, production type and
period are filters in the page.

One template (07_scripts/elizabeth/elizabeth_template.html, the MFT page's look: its styles are copied in at the build), two outputs:
- 03_reports/FTO2_Elizabeth.html: the page with its own copy of the two tables (05_outputs/fto2_dash_nc.csv, fto2_dash_defects.csv);
- 03_reports/skywise/elizabeth/: the same page for a Slate code sandbox, fed by the queries q_fto2_nc and q_fto2_def (the datasets
  the Skywise notebook writes), as the MFT's Slate version.
Both turn the tables into the page's data in the browser (elzFromTables), so they cannot differ.

    python3 -I 07_scripts/elizabeth/build_elizabeth.py
"""
import json
import os
import re
import shutil
import sys

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "03_reports", "skywise", "elizabeth")
L3 = os.path.join(ROOT, "03_reports", "skywise", "level3_datasets")
sys.path.insert(0, os.path.join(ROOT, "07_scripts", "mft"))
sys.path.insert(0, os.path.join(ROOT, "build"))
import build_mft as M      # noqa: E402   weekly_volume: MSN per line and week (the reference leaves the low weeks out)
import build_all as B      # noqa: E402   _scope_css
import skywise_pack as SP  # noqa: E402   the one-file layout, the error box styles, the local stand-in for Slate

NC_COLS = ["nc", "created", "line", "plant", "phase", "msn", "station", "title", "type_nc"]
DEF_COLS = ["nc", "cat", "rca", "sub", "subcode", "cable", "text"]


def tables():
    def cols(name, keep):
        t = pd.read_csv(os.path.join(ROOT, "05_outputs", name), dtype=str, keep_default_na=False, encoding="utf-8-sig")
        return {c: t[c].tolist() for c in keep}
    return {"nc": cols("fto2_dash_nc.csv", NC_COLS), "def": cols("fto2_dash_defects.csv", DEF_COLS)}


def base_css():
    """The MFT page's styles (without its alarm styles), and the error / waiting boxes of the Slate pages."""
    t = open(os.path.join(ROOT, "07_scripts", "mft", "mft_template.html"), encoding="utf-8").read()
    css = t.split("<style>", 1)[1].split("</style>", 1)[0].replace("/*@@ALARMCSS@@*/", "")
    return css + "\n" + SP.EXTRA_CSS.replace(".fto2 ", "")


def build(say=print):
    t = open(os.path.join(HERE, "elizabeth_template.html"), encoding="utf-8").read().replace("/*@@BASECSS@@*/", base_css(), 1)
    ref = SP._blob({"vol": M.weekly_volume()})
    T = tables()
    # the page, with its copy of the tables
    page = t.replace("/*@@HEAD@@*/", "window.ELZ_REF = %s;\nwindow.ELZ_TABLES = %s;" % (ref, SP._blob(T)), 1)
    assert "@@" not in page
    for out in (os.path.join(ROOT, "03_reports", "FTO2_Elizabeth.html"), os.path.join(ROOT, "build", "artifacts", "FTO2_Elizabeth.html")):
        os.makedirs(os.path.dirname(out), exist_ok=True)
        open(out, "w", encoding="utf-8").write(page)
    # Slate: CSS scoped to .fto2, the HTML in a .fto2 box, the JS waits for the queries
    stamp = ("FTO2 Tableau Elizabeth for Slate: data from the queries q_fto2_nc and q_fto2_def through the code sandbox's state. "
             "Generated by 07_scripts/elizabeth/build_elizabeth.py; do not edit by hand.")
    css = re.sub(r"/\*.*?\*/", "", t.split("<style>", 1)[1].split("</style>", 1)[0], flags=re.S)
    fonts = re.search(r'<link rel="stylesheet" href="(https://fonts\.googleapis\.com/[^"]+)">', t)
    css = (('/* Fonts: if Slate blocks this address, the page falls back to the system fonts. */\n@import url("%s");\n' % fonts.group(1)) if fonts else "") + B._scope_css(css)
    html = '<div class="fto2">\n%s\n</div>\n' % t[t.index('<div id="fto2-err"'):t.index("<script>")].strip()
    js = "/* %s */\n" % stamp + t[t.index("<script>") + len("<script>"):t.rindex("</script>")].strip().replace("/*@@HEAD@@*/", "window.ELZ_REF = %s;" % ref, 1) + "\n"
    if "{{" in js or "{{" in html or "{{" in css:
        raise SystemExit("Elizabeth: a double brace in the sandbox's code would be read by Slate as a binding")
    one = SP.write_level(OUT, "fto2_elizabeth", stamp, "Tableau Elizabeth - Slate", css, html, js)
    open(os.path.join(OUT, "FTO2_Elizabeth_Slate.html"), "w", encoding="utf-8").write(one)
    json.dump({"nc": "{{q_fto2_nc}}", "def": "{{q_fto2_def}}"}, open(os.path.join(OUT, "state.json"), "w"), indent=2)
    for q in ("q_fto2_nc", "q_fto2_def"):   # the dashboard's level-3 queries, unchanged
        shutil.copyfile(os.path.join(L3, q + ".sql"), os.path.join(OUT, q + ".sql"))
    pre = SP.FAKE_SLATE.replace("@@NC@@", SP._blob(T["nc"])).replace("@@DEF@@", SP._blob(T["def"])).replace("@@DIS@@", "null")
    open(os.path.join(OUT, "preview_local_only.html"), "w", encoding="utf-8").write(one.replace("<!-- ===== HTML START ===== -->", pre + "<!-- ===== HTML START ===== -->", 1))
    say("Elizabeth: page", len(page.encode()) // 1024, "KB | Slate:", {f: os.path.getsize(os.path.join(OUT, f)) // 1024 for f in sorted(os.listdir(OUT)) if not f.endswith(".md")}, "KB")


if __name__ == "__main__":
    build()
